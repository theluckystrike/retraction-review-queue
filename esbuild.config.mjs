import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { writeFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	write: !prod,
});

if (prod) {
	try {
		const result = await context.rebuild();
		// Reject script creation code from dependencies before writing the release bundle.
		for (const output of result.outputFiles) {
			if (/\bcreateElement\s*\(\s*(['"])script\1\s*[,)]/.test(output.text)) {
				throw new Error('The bundle contains script creation code. Replace the dependency that adds it.');
			}
		}
		for (const output of result.outputFiles) await writeFile(output.path, output.contents);
	} finally {
		await context.dispose();
	}
} else {
	await context.watch();
}
